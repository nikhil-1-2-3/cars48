#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# generate-secret.sh
# Fills in k8s/secret.yaml with your real values, base64-encoded.
#
# Usage:
#   chmod +x scripts/generate-secret.sh
#   ./scripts/generate-secret.sh
#
# It will prompt for each value interactively.
# The resulting k8s/secret.yaml is gitignored — safe to apply, unsafe to commit.
# ─────────────────────────────────────────────────────────────────────────────

set -e

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/k8s/secret.yaml"

b64() { echo -n "$1" | base64 -w 0; }

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  RentHere — Kubernetes Secret Generator"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# ── DATABASE_URL ──────────────────────────────────────
echo "→ RDS Endpoint (e.g. renthere-db.abc123.ap-south-1.rds.amazonaws.com):"
read -r RDS_ENDPOINT
echo "→ RDS Password (master password you set in AWS):"
read -rs RDS_PASSWORD
echo ""
DB_URL="postgresql://cars48_user:${RDS_PASSWORD}@${RDS_ENDPOINT}:5432/cars48_db?schema=public"

# ── JWT_SECRET ────────────────────────────────────────
echo "→ Generating JWT_SECRET automatically (openssl)..."
JWT_SECRET_VAL=$(openssl rand -base64 64 | tr -d '\n')
echo "  Generated: ${JWT_SECRET_VAL:0:20}... (truncated for display)"

# ── Google OAuth ──────────────────────────────────────
echo ""
echo "→ Google OAuth Client ID (from console.cloud.google.com):"
read -r GOOGLE_ID

# ── Razorpay ──────────────────────────────────────────
echo "→ Razorpay Key ID (rzp_live_... or rzp_test_...):"
read -r RAZORPAY_ID
echo "→ Razorpay Key Secret:"
read -rs RAZORPAY_SECRET
echo ""

# ── Email / SMTP ──────────────────────────────────────
echo "→ SMTP Host (e.g. smtp.gmail.com):"
read -r EMAIL_HOST
echo "→ SMTP Port (default 587):"
read -r EMAIL_PORT
EMAIL_PORT="${EMAIL_PORT:-587}"
echo "→ SMTP Username / Email address:"
read -r EMAIL_USER
echo "→ SMTP Password / Gmail App Password:"
read -rs EMAIL_PASS
echo ""
echo "→ From Email address (e.g. noreply@yourdomain.com):"
read -r FROM_EMAIL

# ── Frontend URL (Vercel) ─────────────────────────────
echo "→ Vercel Frontend URL (e.g. https://your-app.vercel.app):"
read -r FRONTEND_URL

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Writing $OUT ..."
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

cat > "$OUT" <<EOF
# ⚠️  AUTO-GENERATED — DO NOT COMMIT ⚠️
# Generated by scripts/generate-secret.sh on $(date)
apiVersion: v1
kind: Secret
metadata:
  name: renthere-secrets
type: Opaque
data:
  PORT: $(b64 "5000")
  NODE_ENV: $(b64 "production")
  DATABASE_URL: $(b64 "$DB_URL")
  JWT_SECRET: $(b64 "$JWT_SECRET_VAL")
  JWT_EXPIRE: $(b64 "30d")
  GOOGLE_CLIENT_ID: $(b64 "$GOOGLE_ID")
  RAZORPAY_KEY_ID: $(b64 "$RAZORPAY_ID")
  RAZORPAY_KEY_SECRET: $(b64 "$RAZORPAY_SECRET")
  EMAIL_HOST: $(b64 "$EMAIL_HOST")
  EMAIL_PORT: $(b64 "$EMAIL_PORT")
  EMAIL_USER: $(b64 "$EMAIL_USER")
  EMAIL_PASS: $(b64 "$EMAIL_PASS")
  FROM_EMAIL: $(b64 "$FROM_EMAIL")
  FRONTEND_URL: $(b64 "$FRONTEND_URL")
EOF

echo ""
echo "✅  $OUT written."
echo ""
echo "Next step — apply to your cluster:"
echo "  kubectl apply -f k8s/secret.yaml"
echo ""
echo "⚠️  This file is gitignored. Keep it secure."
